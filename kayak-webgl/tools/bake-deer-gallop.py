"""Bake Quaternius Deer.gltf (CC0) to joint positions for Riverlight.

Usage: python3 tools/bake-deer-gallop.py /path/to/Deer.gltf > src/deer-gallop.ts
Source: https://quaternius.com/packs/ultimateanimatedanimals.html
"""
import base64
from bisect import bisect_right
import json
import math
from pathlib import Path
import struct
import sys

path = Path(sys.argv[1])
gltf = json.loads(path.read_text())
buffers = [
    base64.b64decode(b["uri"].split(",", 1)[1])
    if b["uri"].startswith("data:") else (path.parent / b["uri"]).read_bytes()
    for b in gltf["buffers"]
]

def accessor(index):
    a = gltf["accessors"][index]
    view = gltf["bufferViews"][a["bufferView"]]
    assert a["componentType"] == 5126
    width = {"SCALAR": 1, "VEC3": 3, "VEC4": 4}[a["type"]]
    offset = view.get("byteOffset", 0) + a.get("byteOffset", 0)
    stride = view.get("byteStride", width*4)
    return [struct.unpack_from("<" + "f"*width, buffers[view["buffer"]], offset+i*stride)
            for i in range(a["count"])]

def qmul(a, b):
    x, y, z, w = a
    i, j, k, l = b
    return (w*i+x*l+y*k-z*j, w*j-x*k+y*l+z*i,
            w*k+x*j-y*i+z*l, w*l-x*i-y*j-z*k)

def rotate(q, p):
    return qmul(qmul(q, (*p, 0)), (-q[0], -q[1], -q[2], q[3]))[:3]

nodes = gltf["nodes"]
ids = {n["name"]: i for i, n in enumerate(nodes)}
parents = {child: i for i, n in enumerate(nodes) for child in n.get("children", [])}
clip = next(a for a in gltf["animations"] if a["name"] == "Gallop")
tracks = {}
for channel in clip["channels"]:
    sampler = clip["samplers"][channel["sampler"]]
    assert sampler.get("interpolation", "LINEAR") == "LINEAR"
    node = channel["target"]
    tracks[node["node"], node["path"]] = (
        [a[0] for a in accessor(sampler["input"])], accessor(sampler["output"])
    )
duration = max(t[-1] for t, _ in tracks.values())

def sample(t):
    cache = {}
    def world(i):
        if i in cache:
            return cache[i]
        def component(name, fallback):
            if (i, name) not in tracks:
                return nodes[i].get(name, fallback)
            times, keys = tracks[i, name]
            right = bisect_right(times, t)
            if right == 0: return keys[0]
            if right == len(times): return keys[-1]
            a, b = keys[right-1], keys[right]
            if name == "rotation" and sum(x*y for x,y in zip(a,b)) < 0:
                b = [-v for v in b]
            f = (t-times[right-1])/(times[right]-times[right-1])
            mixed = [x+(y-x)*f for x,y in zip(a,b)]
            if name == "rotation":
                length = math.sqrt(sum(x*x for x in mixed))
                return [v/length for v in mixed]
            return mixed
        position = component("translation", (0,0,0))
        rotation = component("rotation", (0,0,0,1))
        scale = component("scale", (1,1,1))
        if i in parents:
            p, r, s = world(parents[i])
            position = tuple(x+y for x,y in zip(p, rotate(r, [x*y for x,y in zip(s,position)])))
            rotation = qmul(r, rotation)
            scale = tuple(x*y for x,y in zip(s, scale))
        cache[i] = (position, rotation, scale)
        return cache[i]
    return lambda name: world(ids[name])[0]

def joints(pose, front, side):
    if front:
        # The foreleg has only two visible segments in the source. The
        # target draws the bottom of the shin with a separate dark mesh.
        shoulder, knee, foot = [pose(name + "." + side)
                                for name in ("FrontUpperLeg", "FrontLowerLeg", "FF")]
        fetlock = tuple(a + (b-a)*.78 for a, b in zip(knee, foot))
        return shoulder, knee, fetlock, foot
    return [pose(name + "." + side)
            for name in ("BackShoulder", "BackUpperLeg", "BackLowerLeg", "FFB")]

# The source rig is roughly twice as large as the Riverlight deer.
def height(y):
    return .01 + y*.48

frames = []
for i in range(24):
    pose = sample(duration*i/24)
    front = tuple(sum(pose("FrontShoulder."+s)[k] for s in "LR")/2 for k in (1,2))
    back = tuple(sum(pose("BackShoulder."+s)[k] for s in "LR")/2 for k in (1,2))
    center = ((front[0]+back[0])/2,(front[1]+back[1])/2)
    pitch = math.atan2(back[0]-front[0],front[1]-back[1])
    head = pose("Head")
    values = [height(center[0]), pitch, height(head[1])-.10,
              (head[2]-center[1])*.45-.10]
    for front_leg, side in [(False,"R"),(False,"L"),(True,"R"),(True,"L")]:
        for joint, (x,y,z) in enumerate(joints(pose,front_leg,side)):
            x *= .48
            if joint == 0:
                x = (.16 if front_leg else .185) * (-1 if side == "R" else 1)
            values.extend([x, max(.035,height(y)) if joint == 3 else height(y),
                           (z-center[1])*.45])
    frames.append(values)

print("// Quaternius, Deer / Gallop (CC0 1.0). Generated by tools/bake-deer-gallop.py.")
print("// Torso height, pitch, head Y/Z; then hind R/L, front R/L (hip to hoof).")
print("// Distance per loop, fitted to horizontal hoof travel during contact.")
print("export const GALLOP_STRIDE = 3")
print("export const gallopFrames: readonly (readonly number[])[] = [")
for frame in frames:
    print("    [" + ", ".join(f"{v:.3f}" for v in frame) + "],")
print("]")
